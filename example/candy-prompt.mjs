/**
 * 糖果题的共享素材：题面、"不要调工具"指令、判分正则。
 *
 * example/candy-eval.mjs（model-adapters / dsh-agent 链路）与根目录下的
 * codex_candy_eval.mjs（本地 codex CLI 链路）都从这里取，避免题面在两处各自漂移：
 * 题面必须逐字节一致，否则跨链路的耗时 / token / 正确率没有可比性。
 */

/** 题面正文，不含任何指令；作为 user 内容发给模型。 */
export const CANDY_QUESTION = `在一个黑色的袋子里放有三种口味的糖果，每种糖果有两种不同的形状（圆形和五角星形，不同的形状靠手感可以分辨）。现已知不同口味的糖和不同形状的数量统计如下表。参赛者需要在活动前决定摸出的糖果数目，那么，最少取出多少个糖果才能保证手中同时拥有不同形状的苹果味和桃子味的糖？（同时手中有圆形苹果味匹配五角星桃子味糖果，或者有圆形桃子味匹配五角星苹果味糖果都满足要求）

        苹果味  桃子味  西瓜味
圆形       7      9      8
五角星形   7      6      4
`;

/**
 * "不要调工具"的指令文本，两条链路共用同一句措辞。
 *
 * candy-eval 把它放在 system 里，并额外传 tools: [] 硬禁工具；codex CLI 既没有
 * system 入口也无法清空工具清单，只能并进 user 内容——这是两条链路唯一无法抹平
 * 的上下文差异（codex 侧只是"要求不调"，不是"没有工具可调"）。
 */
export const NO_TOOL_INSTRUCTION = "只回答用户提出的问题，不要调用任何工具。";

/** codex CLI 的输入：指令 + 空行 + 题面。 */
export const CODEX_PROMPT = `${NO_TOOL_INSTRUCTION}\n\n${CANDY_QUESTION}`;

/**
 * 正确答案为 21。
 *
 * 关键前提：题面说"不同的形状靠手感可以分辨"——摸的时候**能自己选形状**，
 * 只有口味是随机的。所以这是"我方定形状、对手定口味"的博弈，不是闭眼随机摸
 * （闭眼摸的答案会是 29，别算错模型）。
 *
 * 最优策略（两阶段）：
 *   1. 先摸星形，直到同时拿到星苹果 + 星桃：最坏 4 个星西瓜 + 7 个星苹果 + 1 = 12 个；
 *   2. 此时任一"圆形苹果 / 圆形桃子"都能配对（圆苹果配星桃，圆桃配星苹果），
 *      再摸圆形直到拿到苹果或桃子：最坏 8 个圆西瓜 + 1 = 9 个。
 *   合计 12 + 9 = 21。（反过来先摸圆形要 18 + 5 = 23，更差。）
 *
 * 21 是最优解：把六种糖果的已取数量当状态做极小化极大 DP，初态的值就是 21。
 *
 * 判分：回答里出现独立的 "21"（前后非数字）即判对。只认阿拉伯数字，"二十一个"
 * 这类写法会被判错；反过来推理过程里若出现过 21 也会判对——两条链路口径一致，
 * 存疑时用 --debug 看全文。
 */
export const ANSWER_PATTERN = /(?<!\d)21(?!\d)/;
